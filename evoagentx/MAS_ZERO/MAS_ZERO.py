    def execute(self, 
            goal: str, 
            existing_agents: Optional[List[Agent]] = None, 
            iteration_num: int = 5) -> str:
        """
        Execute the MAS_ZERO process to achieve the specified goal.
        
        Args:
            goal: The high-level objective to be accomplished.
            evaluator: The evaluator object used for scoring.
            benchmark: The benchmark dataset used for evaluation.
            sample_n: Number of samples used for evaluation.
            existing_agents: Optional list of pre-defined agents to be used in the workflow.
            iteration_num: Number of iterations for refining the workflow and agent assignments.

        Returns:
            final_answer: The best answer selected after self-verification.
            final_score: The evaluation metrics associated with the final answer.
        """

        if not goal or len(goal.strip()) < 10:
            raise ValueError("Goal must be at least 10 characters and descriptive.")
        if iteration_num < 1:
            raise ValueError("`iteration_num` must be a positive integer.")

        self.init_module()
        self.get_tool_info()
        history, suggestion = None, None
        # or_existing_agents = existing_agents if existing_agents else []
        candidate_answers = []
        logger.info(f"Generating workflow for the goal: {goal} | Total iterations: {iteration_num} |Existing agents: {existing_agents}")
        # logger.info(f"Loaded tools: {self.tool_info}")

        for i in range(iteration_num):
            try:
                # logger.info(f"Iteration {i+1}/{iteration_num} — generating workflow for the goal: {goal}...")
                graph = self.generate_workflow(goal=goal, existing_agents=existing_agents, history=history, suggestion=suggestion)

                agent_manager = self.agent_manager
                agent_manager.update_agents_from_workflow(graph, llm_config=self.executor_llm.config)
                workflow = WorkFlow(graph=graph, agent_manager=agent_manager, llm=self.executor_llm, max_execution_steps=10)
        
                # logger.info("Workflow successfully generated. Executing agents...")
                result, added_retries = self._execute_with_retry(
                    operation_name="Executing workflow",
                    operation=workflow.execute,
                    retries_left=2
                )
                # result = workflow.execute()
                candidate_answers.append(result)
                # logger.info(f"Iteration {i+1} completed. Result:\n{result}")

                if i == iteration_num - 1:
                    break  # No need for meta-feedback on the last iteration 

                history = graph.get_workflow_description()
                # suggestion = self.meta_feedback(goal=goal, workflow=workflow)
                suggestion, added_retries = self._execute_with_retry(
                    operation_name="Generating meta-feedback",
                    operation=self.meta_feedback,
                    retries_left=2,
                    goal=goal,
                    workflow=workflow
                )
                # existing_agents = or_existing_agents + agent_manager.agents
                # logger.info(f"History for this iteration: {history}")
                # logger.info(f"Meta-feedback for next iteration: {suggestion}")
            
            except Exception as e:
                logger.warning(f"Iteration {i+1} failed for goal {goal[:50]}... : {e}")
                continue

        if not candidate_answers:
            logger.warning("All iterations failed — no valid candidate answers for self-verification.")
            return "No valid answer generated."

        logger.info("All iterations complete. Proceeding to self-verification...")
        final_answer, added_retries = self._execute_with_retry(
            operation_name="Selecting final answer via self-verification",
            operation=self.self_verification,
            retries_left=1,
            goal=goal,
            candidate_answers=candidate_answers
        )
        # final_answer = self.self_verification(goal=goal, candidate_answers=candidate_answers)
        # logger.info(f"Final answer selected:\n{final_answer}")
        
        return final_answer

    def _execute_with_retry(self, operation_name: str, operation, retries_left: int = 2, **kwargs):
        """Helper method to execute operations with retry logic.
        
        Args:
            operation_name: Name of the operation for logging
            operation: Callable that performs the operation
            retries_left: Number of retry attempts remaining
            **kwargs: Additional arguments to pass to the operation
            
        Returns:
            Tuple of (operation_result, number_of_retries_used)
            
        Raises:
            ValueError: If operation fails after all retries are exhausted
        """
        cur_retries = 0
        # logger.info(f"[DEBUG] executing {operation_name} with kwargs: {kwargs}")
        for k in kwargs.keys():
            if not isinstance(k, str):
                logger.error(f"Non-string key found in kwargs: {repr(k)} (type={type(k)})")

        while cur_retries <= retries_left:  # Changed < to <= to include the initial try
            try:
                logger.info(f"{operation_name} (attempt {cur_retries + 1}/{retries_left + 1}) ...")
                result = operation(**kwargs)
                return result, cur_retries
            except Exception as e:
                if cur_retries == retries_left:
                    raise ValueError(f"Failed to {operation_name} after {cur_retries + 1} attempts.\nError: {e}")
                sleep_time = 2 ** cur_retries
                logger.error(f"Failed to {operation_name} in {cur_retries + 1} attempts. Retry after {sleep_time} seconds.\nError: {e}")
                time.sleep(sleep_time)
                cur_retries += 1
    
    def generate_workflow(self, 
                          goal: str, 
                          existing_agents: Optional[List[Agent]] = None, 
                          history: Optional[str] = None, 
                          suggestion: Optional[str] = None,
                          retry: int = 2, 
                          **kwargs
                          ) -> WorkFlowGraph:

        plan_history = "" if history is None else history
        plan_suggestion = "" if suggestion is None else suggestion

        # Generate the initial workflow plan
        cur_retries = 0
        plan, added_retries = self._execute_with_retry(
            operation_name="Generating a workflow plan",
            operation=self.generate_plan,
            retries_left=retry,
            goal=goal,
            history=plan_history,
            suggestion=plan_suggestion
        )
        cur_retries += added_retries

        # Build workflow from plan
        workflow, added_retries = self._execute_with_retry(
            operation_name="Building workflow from plan",
            operation=self.build_workflow_from_plan,
            retries_left=retry - cur_retries,
            goal=goal,
            plan=plan
        )
        cur_retries += added_retries

        # Validate initial workflow structure
        logger.info("Validating initial workflow structure...")
        workflow._validate_workflow_structure()
        # logger.info(f"Successfully generate the following workflow:\n{workflow.get_workflow_description()}")

        # generate / assigns the initial agents
        # logger.info("Generating agents for the workflow ...")
        workflow, added_retries = self._execute_with_retry(
            operation_name="Generating agents for the workflow",
            operation=self.generate_agents,
            retries_left=retry - cur_retries,
            goal=goal,
            graph=workflow,
            existing_agents=existing_agents,
            history=history,
            suggestion=suggestion
        )

        # Validate workflow after agent generation
        # logger.info("Validating workflow after agent generation...")
        workflow._validate_workflow_structure()
        # Validate that all nodes have agents
        for node in workflow.nodes:
            if not node.agents:
                raise ValueError(f"Node {node.name} has no agents assigned after agent generation")

        return workflow

