    def generate_agents(
        self, 
        goal: str, 
        graph: WorkFlowGraph,
        existing_agents: Optional[List[Agent]] = None,
        history: Optional[str] = None, 
        suggestion: Optional[str] = None
    ) -> WorkFlowGraph:
        
        history = "" if history is None else history
        suggestion = "" if suggestion is None else suggestion
        existing_agents = [] if existing_agents is None else existing_agents
        agent_generator: AgentGenerator = self.agent_generator
        workflow_desc = graph.get_workflow_description()
        agent_generation_action_name = agent_generator.agent_generation_action_name
        agent_fields = ["name", "description", "inputs", "outputs", "prompt", "tool_names"]
        agents_data = [{key: value for key, value in agent.to_dict(ignore=["class_name"]).items() if key in agent_fields} for agent in existing_agents]
        agents_desc = json.dumps(agents_data, indent=4)
        for subtask in graph.nodes:
            subtask_fields = ["name", "description", "reason", "inputs", "outputs"]
            subtask_data = {key: value for key, value in subtask.to_dict(ignore=["class_name"]).items() if key in subtask_fields}
            subtask_desc = json.dumps(subtask_data, indent=4)
            agent_generation_action_data = {"goal": goal, "workflow": workflow_desc, "task": subtask_desc, "existing_agents": agents_desc, "history": history, "suggestion": suggestion}
            # logger.info(f"Generating agents for subtask: {subtask_data['name']}")
            agents: AgentGenerationOutput = agent_generator.execute(
                action_name=agent_generation_action_name, 
                action_input_data=agent_generation_action_data,
                return_msg_type=MessageType.RESPONSE
            ).content
            # logger.info(f"Raw LLM output before parsing:\n{agents}")

            all_agents = []
            for agent in agents.generated_agents:
                agent_dict = agent.to_dict(ignore=["class_name"])
                all_agents.append(agent_dict)

            for name in agents.selected_agents:
                for agent in existing_agents:
                    if agent.name == name:
                        agent_dict = agent.to_dict(ignore=["class_name"])
                        all_agents.append(agent_dict)
                        break
                else:
                    logger.warning(f"Selected agent {name} not found in existing agents.")
            subtask.set_agents(agents=all_agents)
        
        return graph
    
    def build_workflow_from_plan(self, goal: str, plan: TaskPlanningOutput) -> WorkFlowGraph:
        nodes: List[WorkFlowNode] = plan.sub_tasks
        # infer edges from sub-tasks' inputs and outputs
        edges: List[WorkFlowEdge] = []
        for node in nodes:
            for another_node in nodes:
                if node.name == another_node.name:
                    continue
                node_output_params = [param.name for param in node.outputs]
                another_node_input_params = [param.name for param in another_node.inputs]
                if any([param in another_node_input_params for param in node_output_params]):
                    edges.append(WorkFlowEdge(edge_tuple=(node.name, another_node.name)))
        graph = WorkFlowGraph(goal=goal, nodes=nodes, edges=edges)
        return graph
    
    def meta_feedback(self, goal: str, workflow: WorkFlow) -> MetaFeedbackOutput:
        meta_controller: MetaController = self.meta_controller
        meta_feedback_action_name = meta_controller.meta_feedback_action_name
        workflow_desc = workflow.graph.get_workflow_description()
        suggestion = []

        def get_node_io(workflow: WorkFlow, node_name: str):
            messages = workflow.environment.get_task_messages(tasks=node_name, include_inputs=True)
            inputs = [m.content for m in messages if m.msg_type == MessageType.INPUT]
            outputs = [m.content for m in messages if m.msg_type == MessageType.RESPONSE]
            return inputs, outputs

        def get_agent_io(workflow: WorkFlow, agent_name, task_name=None):
            inputs = []
            outputs = []
            for m in workflow.environment.get():
                if m.agent == agent_name:
                    if task_name is None or m.wf_task == task_name:
                        if m.msg_type == MessageType.INPUT:
                            inputs.append(m.content)
                        elif m.msg_type == MessageType.RESPONSE:
                            outputs.append(m.content)
            return inputs, outputs

        for node in workflow.graph.nodes:
            subtask_level_pairs = []
            agent_level_pairs = []
            for agent in node.agents:
                inputs, outputs = get_agent_io(workflow, agent["name"])
                agent_level_pairs.append({"agent": agent["name"], "inputs": inputs, "outputs": outputs})
            inputs, outputs = get_node_io(workflow, node.name)
            subtask_level_pairs.append({"task": node.name, "inputs": inputs, "outputs": outputs})
            meta_feedback_action_data = {"goal": goal, "workflow": workflow_desc, "subtask_level_pairs": subtask_level_pairs, "agent_level_pairs": agent_level_pairs}
            message: Message = meta_controller.execute(
                action_name=meta_feedback_action_name,
                action_input_data=meta_feedback_action_data,
                return_msg_type=MessageType.REQUEST
            ).content
            suggestion.append(message)
        
        def clean_meta_feedback(suggestion):
            if isinstance(suggestion, list):
                suggestion = [re.sub(r"^```json\s*|\s*```$", "", s.content.strip()) for s in suggestion]
                return "\n\n".join(suggestion)
            return suggestion
        
        final_suggestion = clean_meta_feedback(suggestion)

        return final_suggestion
    
    def self_verification(self, goal: str, candidate_answers: List[str]) -> str:
        if candidate_answers is None:
            raise ValueError("`candidate_answers` to `self_verification` cannot be None")
        # logger.info(f"目前的备选答案有：\n{candidate_answers}...")
        self_verifier: SelfVerifier = self.self_verifier
        self_verification_action_name = self_verifier.self_verification_action_name
        self_verification_action_data = {"goal": goal, "candidate_answers": candidate_answers}
        message: Message = self_verifier.execute(
            action_name=self_verification_action_name,
            action_input_data=self_verification_action_data,
            return_msg_type=MessageType.RESPONSE
        )

        return message.content.final_answer

